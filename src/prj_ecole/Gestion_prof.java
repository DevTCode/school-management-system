    private void btnSaveNotesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveNotesActionPerformed
        // TODO add your handling code here:
    DefaultTableModel model = new DefaultTableModel(); 
    model.setColumnIdentifiers(new Object[]{"Nom_class", "ID", "Nom", "Prénom", "Nom_module", "Session_exam", "ID_exam", "Type_exam","Note"});

    try {
        Connection cnx = Config.getConnection();
        
        //pour que chaque instruction sql sera validée automatiquement apres son execution
        cnx.setAutoCommit(true);

        String query = "SELECT Class.Nom_class, Etudiant.Id_etud, Etudiant.Nom, Etudiant.Prenom, Module.Nom_module, Examen.Session_exam, Examen.Id_exam, Examen.Type_exam, Note.Note "
                + "FROM Etudiant "
                + "INNER JOIN Class ON Etudiant.Id_class = Class.Id_class "
                + "INNER JOIN Module ON Class.Id_class = Module.Id_class "
                + "INNER JOIN Examen ON Examen.Id_module = Module.Id_module "
                + "LEFT JOIN Note ON Etudiant.Id_etud = Note.Id_etud AND Examen.Id_exam = Note.Id_exam "
                + "WHERE Nom_class LIKE ? AND Nom_module LIKE ? AND Session_exam LIKE ? AND Type_exam LIKE ?";

        try (PreparedStatement queryCommand = cnx.prepareStatement(query)) {
            queryCommand.setString(1, "%" + jComboBox1.getSelectedItem().toString() + "%");
            queryCommand.setString(2, "%" + jComboBox3.getSelectedItem().toString() + "%");
            queryCommand.setString(3, "%" + jComboBox2.getSelectedItem().toString() + "%");
            queryCommand.setString(4, "%" + jComboBox4.getSelectedItem().toString() + "%");

            ResultSet resultSet = queryCommand.executeQuery();

            while (resultSet.next()) {
                String nom = resultSet.getString("Nom_class");
                int id = resultSet.getInt("Id_etud");
                String name = resultSet.getString("Nom");
                String lastname = resultSet.getString("Prenom");
                String CIN = resultSet.getString("Nom_module");
                String Login = resultSet.getString("Session_exam");
                int password = resultSet.getInt("Id_exam");
                String spe = resultSet.getString("Type_exam");
                float noteValue = resultSet.getFloat("Note");
                String note = (resultSet.wasNull()) ? "" : (noteValue == (int) noteValue) ? String.valueOf((int) noteValue) : String.valueOf(noteValue);
                model.addRow(new Object[]{nom, id, name, lastname, CIN, Login, password, spe,note});
            }
            fetchdata.setModel(model);
            hideColumns(fetchdata, 1);
            hideColumns(fetchdata, 6);

            fetchdata.setSelectionBackground(SystemColor.activeCaption);
            fetchdata.setSelectionForeground(Color.BLUE);
        }
    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Une erreur s'est produite ici: " + ex.getMessage());
    }

    }//GEN-LAST:event_btnSaveNotesActionPerformed
