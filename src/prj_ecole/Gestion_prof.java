                + "INNER JOIN Professeur ON Professeur.Id_prof = Module.Id_prof inner join Class on Class.Id_class = Module.Id_class inner join Examen on Examen.Id_module=Module.Id_module "
                + "WHERE Professeur.Id_prof = ? AND Examen.Session_exam = ? and Class.Nom_class = ?";

