    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try {
        Connection cnx = Config.getConnection();
        cnx.setAutoCommit(true);

        
        for (int row = 0; row < fetchdata.getRowCount(); row++) {
            int idEtudiant = (int) fetchdata.getValueAt(row, 1);
            int idExamen = (int) fetchdata.getValueAt(row, 6);

            
            Object noteValueObject = fetchdata.getValueAt(row, 8);

            
            if (noteValueObject != null && noteValueObject instanceof String) {
                
               
                String formattedNote = (String) noteValueObject;
                try {
      
                      float noteValue = Float.parseFloat(formattedNote);

                      String updateNoteQuery = "UPDATE Note SET Note = ? WHERE Id_etud = ? AND Id_exam = ?";
                      try (PreparedStatement updateNoteCommand = cnx.prepareStatement(updateNoteQuery)) {
                           updateNoteCommand.setFloat(1, noteValue);
                           updateNoteCommand.setInt(2, idEtudiant);
                           updateNoteCommand.setInt(3, idExamen);

                           updateNoteCommand.executeUpdate();
                           
                          }
                      } catch (NumberFormatException e) {
                   
                    JOptionPane.showMessageDialog(this, "Erreur lors de la conversion de la note en nombre.");
                }
            }
        }
         JOptionPane.showMessageDialog(this, "Modification effectuée avec succès!", "Confirmation", JOptionPane.INFORMATION_MESSAGE);
    } catch (SQLException ex) {
       
        JOptionPane.showMessageDialog(this, "Une erreur s'est produite ici: " + ex.getMessage());
    }
       
    }//GEN-LAST:event_jButton3ActionPerformed

